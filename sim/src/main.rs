//! `spores-sim [all|baseline|sweep|allowance|wash|vectors|replay-decisions FILE] [--seeds N] [--out DIR] [--max-active N] [--jobs N]`
//!
//! `--max-active N` sets how many spores are active (default 16, at most the
//! collection of 64) and `--jobs N` how many jobs each honest spore posts per
//! epoch (default 3; the testnet agents default to 1). Non-default values add
//! a suffix to every output file name (`sweep-64.json`, `sweep-64-j1.md`, ...),
//! so the default files stay as they are.
//!
//! `all` (default) writes `baseline.json`, `sweep.json`, `sweep.md`,
//! `sweep-full.md` and `phase1-report.md` to the out directory (default `out/`). `vectors` writes
//! `vectors/core.json` and `vectors/agents.json`. `replay-decisions FILE`
//! re-checks an agent decision log against `spores_core::hiring::pick`.
//! `allowance` runs the baseline and the wash gate under each living-allowance
//! candidate and writes `allowance.json` and `allowance.md`. `wash` writes
//! `wash.json` for the Demo Lab's wash panel: the gate with the shipped allowance
//! at every traffic level, with per-epoch series, plus Phase 1's shipped results.

mod agent_vectors;
mod economy;
mod replay;
mod report;
mod rng;
mod vectors;

use std::fs;
use std::path::PathBuf;
use std::process::ExitCode;

use spores_core::Params;

use crate::economy::Scale;

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let mut cmd = "all".to_string();
    let mut seeds = 20u64;
    let mut out = PathBuf::from("out");
    let mut file: Option<PathBuf> = None;
    let mut scale = Scale::DEFAULT;
    let mut i = 0;
    while i < args.len() {
        match args[i].as_str() {
            "--seeds" => {
                i += 1;
                seeds = args.get(i).and_then(|s| s.parse().ok()).expect("--seeds N");
            }
            "--max-active" => {
                i += 1;
                scale.active = args.get(i).and_then(|s| s.parse().ok()).expect("--max-active N");
                assert!((4..=64).contains(&scale.active), "--max-active must be 4..=64");
            }
            "--jobs" => {
                i += 1;
                scale.jobs = args.get(i).and_then(|s| s.parse().ok()).expect("--jobs N");
                assert!(scale.jobs >= 1, "--jobs must be at least 1");
            }
            "--out" => {
                i += 1;
                out = PathBuf::from(args.get(i).expect("--out DIR"));
            }
            other if cmd == "replay-decisions" => file = Some(PathBuf::from(other)),
            other => cmd = other.to_string(),
        }
        i += 1;
    }

    if cmd == "vectors" {
        let path = PathBuf::from("vectors/core.json");
        fs::create_dir_all("vectors").expect("create vectors/");
        let text = serde_json::to_string_pretty(&vectors::generate()).unwrap() + "\n";
        fs::write(&path, text).expect("write vectors");
        println!("wrote {}", path.display());
        let path = PathBuf::from("vectors/agents.json");
        let text = serde_json::to_string_pretty(&agent_vectors::generate()).unwrap() + "\n";
        fs::write(&path, text).expect("write vectors");
        println!("wrote {}", path.display());
        return ExitCode::SUCCESS;
    }

    if cmd == "replay-decisions" {
        let path = file.expect("replay-decisions FILE");
        let text = fs::read_to_string(&path).expect("read decision log");
        let (checked, failures) = replay::replay(&text);
        for f in &failures {
            println!("MISMATCH {f}");
        }
        println!("replayed {checked} decisions: {} match, {} differ", checked - failures.len(), failures.len());
        return if failures.is_empty() && checked > 0 {
            ExitCode::SUCCESS
        } else {
            ExitCode::FAILURE
        };
    }

    let Scale { active, jobs } = scale;
    let (mut suffix, mut flag) = (String::new(), String::new());
    if active != Scale::DEFAULT.active {
        suffix += &format!("-{active}");
        flag += &format!(" --max-active {active}");
    }
    if jobs != Scale::DEFAULT.jobs {
        suffix += &format!("-j{jobs}");
        flag += &format!(" --jobs {jobs}");
    }
    let name = |stem: &str, ext: &str| out.join(format!("{stem}{suffix}.{ext}"));

    if cmd == "allowance" {
        fs::create_dir_all(&out).expect("create out dir");
        let a = report::allowance(seeds, scale);
        fs::write(name("allowance", "json"), serde_json::to_string_pretty(&a.json).unwrap()).unwrap();
        let md = format!(
            "# Living allowance in sim\n\nGenerated by `cargo run --release -p spores-sim -- allowance --seeds {seeds}{flag}`.\n\n{}\nWash gate with the shipped allowance: **{}**\n",
            a.markdown,
            if a.gate_pass { "PASS" } else { "FAIL" }
        );
        fs::write(name("allowance", "md"), &md).unwrap();
        println!("{md}");
        return if a.gate_pass { ExitCode::SUCCESS } else { ExitCode::FAILURE };
    }

    if cmd == "wash" {
        fs::create_dir_all(&out).expect("create out dir");
        // No `--max-active`, `--jobs` or suffix: it walks every traffic level itself.
        let path = out.join("wash.json");
        fs::write(&path, serde_json::to_string(&report::wash()).unwrap()).unwrap();
        println!("wrote {}", path.display());
        return ExitCode::SUCCESS;
    }

    if cmd == "tune" {
        println!("{}", report::tune(seeds));
        return ExitCode::SUCCESS;
    }

    fs::create_dir_all(&out).expect("create out dir");
    let mut report = String::from("# Phase 1 sim results\n\n");
    report.push_str(&format!(
        "Generated by `cargo run --release -p spores-sim -- {cmd} --seeds {seeds}{flag}`. Shipped params: {}.\n\n",
        report::params_line(&Params::shipped())
    ));
    let mut ok = true;

    if cmd == "all" || cmd == "baseline" {
        let b = report::baseline(seeds, scale);
        fs::write(
            name("baseline", "json"),
            serde_json::to_string_pretty(&b.json).unwrap(),
        )
        .unwrap();
        report.push_str("## Baseline: price only vs price with tubes\n\n");
        report.push_str(&b.markdown);
        report.push('\n');
        println!("## Baseline\n\n{}", b.markdown);
    }
    if cmd == "all" || cmd == "sweep" {
        let s = report::sweep(scale);
        fs::write(name("sweep", "json"), serde_json::to_string_pretty(&s.json).unwrap()).unwrap();
        fs::write(name("sweep-full", "md"), &s.full_markdown).unwrap();
        let gate = if s.shipped_pass { "PASS" } else { "FAIL" };
        fs::write(
            name("sweep", "md"),
            format!(
                "# Wash-trading sweep, {active} active, {jobs} jobs per spore per epoch\n\nGenerated by `cargo run --release -p spores-sim -- {cmd} --seeds {seeds}{flag}`.\n\n{}Gate (shipped params, every case with K in range): **{gate}**\n",
                s.markdown
            ),
        )
        .unwrap();
        report.push_str("## Wash-trading sweep (SPEC §9)\n\n");
        report.push_str(&s.markdown);
        report.push_str(&format!(
            "Gate (shipped params, every case with K in range): **{}**\n",
            if s.shipped_pass { "PASS" } else { "FAIL" }
        ));
        println!("## Wash-trading sweep\n\n{}", s.markdown);
        println!("gate: {}", if s.shipped_pass { "PASS" } else { "FAIL" });
        ok = s.shipped_pass;
    }
    fs::write(name("phase1-report", "md"), &report).unwrap();
    println!("wrote {}", name("phase1-report", "md").display());
    if ok {
        ExitCode::SUCCESS
    } else {
        ExitCode::FAILURE
    }
}
